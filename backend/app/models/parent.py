import uuid
from datetime import datetime
from typing import Optional, List

from sqlalchemy import Boolean, DateTime, ForeignKey, String, Text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import TenantBaseModel


class StudentLinkVerificationCode(TenantBaseModel):
    """
    Secure one-time verification tokens generated by administrators to link parents to students.
    """
    __tablename__ = "student_link_verification_codes"

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    student_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("student_profiles.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    code: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    generated_by_user_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    is_used: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    used_by_parent_user_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    used_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    student: Mapped["StudentProfile"] = relationship("StudentProfile")
    generated_by: Mapped[Optional["User"]] = relationship("User", foreign_keys=[generated_by_user_id])
    used_by_parent: Mapped[Optional["User"]] = relationship("User", foreign_keys=[used_by_parent_user_id])


class ParentTeacherMessage(TenantBaseModel):
    """
    Direct asynchronous communication channel between parents and assigned subject/class teachers.
    """
    __tablename__ = "parent_teacher_messages"

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    student_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("student_profiles.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    parent_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    teacher_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    subject: Mapped[str] = mapped_column(String(255), nullable=False)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    sender_role: Mapped[str] = mapped_column(String(20), nullable=False)  # PARENT | TEACHER
    is_read: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    parent_message_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("parent_teacher_messages.id", ondelete="CASCADE"),
        nullable=True,
    )

    student: Mapped["StudentProfile"] = relationship("StudentProfile")
    parent_user: Mapped["User"] = relationship("User", foreign_keys=[parent_user_id])
    teacher_user: Mapped["User"] = relationship("User", foreign_keys=[teacher_user_id])
    replies: Mapped[List["ParentTeacherMessage"]] = relationship(
        "ParentTeacherMessage",
        back_populates="parent_message",
        foreign_keys=[parent_message_id],
    )
    parent_message: Mapped[Optional["ParentTeacherMessage"]] = relationship(
        "ParentTeacherMessage",
        back_populates="replies",
        remote_side="ParentTeacherMessage.id",
        foreign_keys=[parent_message_id],
    )
